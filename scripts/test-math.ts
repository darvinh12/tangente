import { parse, evaluate } from "../src/lib/math/parse";
import { equivalent, sameUnion, parseFiniteSet, sameFiniteSet } from "../src/lib/math/check";
import { poly, frac, terms } from "../src/lib/math/tex";
let fail = 0;
const ok = (c: boolean, m: string) => { if (!c) { fail++; console.log("FAIL", m); } };
const ev = (s: string, sc: Record<string, number> = {}, vars?: string[]) => evaluate(parse(s, { vars: vars ?? Object.keys(sc) }), sc);
ok(ev("\\frac{3}{4}") === 0.75, "frac");
ok(ev("2x+1", { x: 3 }) === 7, "implicit");
ok(ev("x(x+1)", { x: 2 }) === 6, "x(x+1)");
ok(ev("-x^2", { x: 3 }) === -9, "-x^2");
ok(ev("x^{10}", { x: 2 }) === 1024, "x^{10}");
ok(ev("\\sqrt{x}", { x: 9 }) === 3, "sqrt");
ok(Math.abs(ev("\\sqrt[3]{-8}") + 2) < 1e-12, "cbrt neg");
ok(Math.abs(ev("e^{2x}", { x: 1 }) - Math.E ** 2) < 1e-12, "e^{2x}");
ok(Math.abs(ev("\\ln\\left(x\\right)", { x: Math.E }) - 1) < 1e-12, "ln left");
ok(Math.abs(ev("\\ln x^2", { x: Math.E }) - 2) < 1e-12, "ln x^2");
ok(ev("\\log_{2}8") === 3, "log2");
ok(Math.abs(ev("\\log_2\\left(8\\right)") - 3) < 1e-12, "log_2(8)");
ok(ev("\\left|x-3\\right|", { x: 1 }) === 2, "abs");
ok(ev("|x|+|x-1|", { x: -1 }) === 3, "abs2");
ok(ev("2|x|", { x: -2 }) === 4, "2|x|");
ok(ev("\\mleft(x+1\\mright)^2", { x: 1 }) === 4, "mleft");
ok(ev("3\\cdot 4") === 12, "cdot");
ok(ev("2{,}5") === 2.5, "comma");
ok(ev("2,5") === 2.5, "comma2");
ok(ev("-\\infty") === -Infinity, "-inf");
ok(ev("-inf") === -Infinity, "-inf plain");
ok(ev("sqrt(16)/2") === 2, "plain sqrt");
ok(ev("\\frac{x^2-1}{x-1}", { x: 3 }) === 4, "rational");
ok(ev("\\dfrac{1}{2}x", { x: 4 }) === 2, "dfrac");
ok(ev("de+f", { d: 1, e: 2, f: 3 }, ["d","e","f"]) === 5, "e as var");
ok(Math.abs(ev("\\exponentialE^{x}", { x: 0 }) - 1) < 1e-12, "expE");
ok(ev("x^{\\frac{1}{2}}", { x: 4 }) === 2, "x^{1/2}");
ok(Math.abs(ev("\\frac{1}{3}x^{-\\frac{2}{3}}", { x: 8 }) - 1/12) < 1e-12, "neg frac exp");
ok(ev("x^-1", { x: 4 }) === 0.25, "x^-1");
ok(equivalent("2(x+1)", "2x+2", { vars: ["x"] }), "equiv1");
ok(!equivalent("\\sqrt{x^2}", "x", { vars: ["x"] }), "equiv sqrt x^2");
ok(equivalent("\\frac{1}{2\\sqrt{x}}", "\\frac{1}{2}x^{-1/2}", { vars: ["x"], domain: [0.1, 5] }), "equiv deriv");
ok(!equivalent("x^2", "x^3", { vars: ["x"] }), "nonequiv");
ok(equivalent("\\frac{6}{8}", "0.75"), "num eq");
try { parse("x+y", { vars: ["x"] }); ok(false, "vars check"); } catch {}
try { parse("\\frac{\\placeholder{}}{2}"); ok(false, "placeholder"); } catch {}
ok(sameUnion([{lo:-Infinity,hi:1,loClosed:false,hiClosed:false},{lo:1,hi:Infinity,loClosed:false,hiClosed:false}], [{lo:1,hi:Infinity,loClosed:false,hiClosed:false},{lo:-Infinity,hi:1,loClosed:true,hiClosed:false}]), "union");
ok(!sameUnion([{lo:0,hi:1,loClosed:true,hiClosed:false}],[{lo:0,hi:1,loClosed:true,hiClosed:true}]), "union closed");
ok(sameFiniteSet(parseFiniteSet("{1, 2, a}")!, ["a","2","1"]), "set");
ok(poly([1,-3,2]) === "x^{2} - 3x + 2", "poly " + poly([1,-3,2]));
ok(poly([-1,0,1]) === "-x^{2} + 1", "poly2 " + poly([-1,0,1]));
ok(frac(6,-4) === "-\\frac{3}{2}", "frac");
ok(terms([[2,"x"],[-1,"\\sqrt{x}"],[5,""]]) === "2x - \\sqrt{x} + 5", "terms");
console.log(fail ? `${fail} fallas` : "todo bien");
